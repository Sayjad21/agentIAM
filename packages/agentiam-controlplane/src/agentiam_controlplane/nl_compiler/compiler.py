"""NL to Cedar Compiler module.

Two compilers behind one call. The model (hosted by default, ADR-040) handles any sentence;
the offline template matcher (`templates.py`, APICTA-01 Part D) handles the demo's policy
shapes when the model is unreachable, too slow, gives an unusable answer, or is switched off.
The output says which one answered and, for a fallback, why.

Given the current policy, the model is asked for the **whole updated policy** and a template's
statements are appended to it, so what the console tests and activates is a complete policy.
Measured before: every single-rule policy scored 27/51 on the corpus gate standalone, so no
English sentence could be activated at all.
"""

import asyncio
import hashlib
import logging
from decimal import Decimal
from typing import Any, Literal

from pydantic import BaseModel, Field, ValidationError
from pydantic.json_schema import SkipJsonSchema

from agentiam_controlplane.nl_compiler.llm import LLMClient, LLMError, client_from_env
from agentiam_core.policy_testing import PolicyTestCase

logger = logging.getLogger(__name__)

#: A statement is user-authored English that may name individuals or amounts. Logging it
#: verbatim leaks whatever the operator typed into their console (`ENGINEERING-RULES`
#: rule 10, `PLAN.md` NFR-5). The digest is a correlation handle across the compile
#: request, its evaluation, and the audit record — the same reason spec 10 §7's
#: ``arg_digest`` exists. It is also what a published policy bundle records (spec 05 §5.7.3).
_STATEMENT_DIGEST_BYTES = 8


def statement_digest(statement: str) -> str:
    """A short, stable handle for a natural-language statement, suitable for logs."""
    return hashlib.sha256(statement.encode("utf-8")).hexdigest()[: _STATEMENT_DIGEST_BYTES * 2]


class CompilerTestCase(BaseModel):
    """A test case generated by the compiler to verify its own policy output.

    The fields mirror `agentiam_core.policy_testing.PolicyTestCase`, so a generated test
    is evaluated through exactly the same path as the 51-case corpus and the activation
    gate. The previous shape named a principal id and a resource type, which could only
    be checked against an empty entity list — so those tests turned on guessing ids
    rather than on the policy being right (STATUS gap 19).
    """

    name: str = Field(..., description="A short, descriptive name for the test.")
    description: str = Field(..., description="What the test is asserting.")
    expected: bool = Field(
        ..., description="True if the request should be allowed, False if denied."
    )
    role: str = Field(default="worker", description="The agent's role, e.g. 'worker' or 'senior'.")
    operation: str = Field(..., description="The scope attempted, e.g. 'invoice:read'.")
    tool: str = Field(
        default="invoice_api",
        description="One of invoice_api, vendor_api, payment_api, email_internal, email_external.",
    )
    amount: str = Field(default="0", description="Payment amount as a decimal string, e.g. '5000'.")
    depth: int = Field(default=1, description="The agent's delegation depth, 1 for a root agent.")
    elevated: bool = Field(default=False, description="Whether an approver elevated the request.")
    environment: str = Field(default="production", description="Usually 'production'.")
    agent_id: str = Field(
        default="agt-1", description="The agent making the request, for a rule about one agent."
    )

    def as_policy_test_case(self) -> PolicyTestCase:
        """The core `PolicyTestCase` this describes, for the shared evaluator."""
        return PolicyTestCase(
            name=self.name,
            description=self.description,
            operation=self.operation,
            expected=self.expected,
            role=self.role,
            tool=self.tool,
            amount=Decimal(self.amount or "0"),
            depth=self.depth,
            elevated=self.elevated,
            environment=self.environment,
            agent_id=self.agent_id,
        )


class CompilerOutput(BaseModel):
    """The structured output from the NL->Policy compiler."""

    clarifying_question: str | None = Field(
        default=None,
        description="Ask a question if input is ambiguous. Only set if you cannot guess.",
    )
    cedar_source: str | None = Field(
        default=None,
        description="The compiled Cedar policy source code. Omit if asking a clarifying question.",
    )
    tests: list[CompilerTestCase] = Field(
        default_factory=list,
        description="Test cases to verify the policy. Omit if ambiguous. Must include Allow/Deny.",
    )
    #: Which compiler answered. Kept out of the schema the model sees, and overwritten after
    #: the model's answer is parsed — a label the model could set would label nothing.
    #: Excluded from dumps as well, so the model-facing shape stays exactly three fields
    #: (`tests/security/test_redteam_suite.py` A-26 pins that).
    compiled_by: SkipJsonSchema[Literal["model", "template"]] = Field(default="model", exclude=True)
    #: Why the template compiler answered instead of the model, when it did.
    fallback_reason: SkipJsonSchema[str | None] = Field(default=None, exclude=True)


_SYSTEM_PROMPT = """You are a Cedar policy compiler for AgentIAM. Translate the requirement
into a Cedar policy over the fixed schema below, and generate test cases for it.

THE SCHEMA IS FIXED. Never invent entity types.

  principal  Agent   attributes: role (string), depth (number)
  resource   Tool    attributes: sensitivity ("low"|"medium"|"critical"),
                                 is_external (boolean), server (string)
  action     the scope string, e.g. Action::"invoice:read"
  context            amount (decimal), elevated (boolean), environment (string)

Known tools: invoice_api, vendor_api, payment_api, email_internal, email_external.
Common roles: worker, senior, auditor. Common scopes: invoice:read, invoice:write,
vendor:read, payment:initiate, email:send.

WRITE POLICIES ABOUT ROLES, NOT INDIVIDUALS. "Managers can approve expenses" is
principal.role == "manager", never a named agent id.

SYNTAX RULES — these are the exact mistakes measured on earlier runs. Read them twice.

1. **Cedar uses `&&` and `||`. It has no `and` / `or` keywords.** Writing `and` is a
   parse error and was the single largest cause of failure.
   Wrong: when { principal.role == "senior" and context.amount.lessThan(decimal("10.0")) };
   Right: when { principal.role == "senior" && context.amount.lessThan(decimal("10.0")) };
2. **Only `context.amount` is a decimal.** Compare it with decimal methods. Everything
   else — including `principal.depth` — is an ordinary number compared with < <= > >= ==.
   Wrong: principal.depth.lessThan(3)
   Right: principal.depth < 3
3. Leave a scope element unconstrained by writing it bare. Use `resource`, NEVER
   `resource == Resource::*` or `resource in Tool::*`. There is no `::*` in Cedar.
4. Every condition goes in a `when { }` clause after the scope, never inside the scope.
   Wrong: permit(principal, action, resource == Tool::"x" && x.sensitivity == "low");
   Right: permit(principal, action, resource) when { resource.sensitivity == "low" };
5. Money comparisons:
   context.amount.lessThanOrEqual(decimal("500000.0"))   for "at most" / "up to"
   context.amount.lessThan(decimal("10000.0"))           for "below" / "under"
6. Several actions: action in [Action::"invoice:read", Action::"vendor:read"].
7. **A `forbid` alone denies everything, because nothing permits.** "No agent may use an
   external tool" still needs a permit for what remains allowed:
   permit(principal, action, resource);
   forbid(principal, action, resource) when { resource.is_external };
8. Negate booleans with `!`, as in `!resource.is_external`.
9. Every policy ends with a semicolon.
10. Two different rules are two separate policies, not one policy with `||`. "Seniors up
    to 1000000, everyone else up to 1000" is two permits.

WHEN TO ASK INSTEAD OF COMPILING:
Ask a `clarifying_question` ONLY if the requirement names no actor at all, or no action at
all, or contradicts itself. Do NOT ask merely because a role or resource is generic —
"agents", "any agent", "senior agents" are all perfectly clear. If you can identify who and
what, COMPILE IT.

EXAMPLES

Requirement: Auditor agents may send email.
permit(principal, action == Action::"email:send", resource)
when { principal.role == "auditor" };

Requirement: Agents may initiate payments of at most 7500.
permit(principal, action == Action::"payment:initiate", resource)
when { context.amount.lessThanOrEqual(decimal("7500.0")) };

Requirement: Agents may read vendor records, but never on a critical tool.
permit(principal, action == Action::"vendor:read", resource);
forbid(principal, action, resource) when { resource.sensitivity == "critical" };

Requirement: Auditor agents may read vendor records at depth 4 or shallower.
permit(principal, action == Action::"vendor:read", resource)
when { principal.role == "auditor" && principal.depth <= 4 };

Requirement: Senior agents may send email anywhere; everyone else only internally.
permit(principal, action == Action::"email:send", resource)
when { principal.role == "senior" };
permit(principal, action == Action::"email:send", resource)
when { principal.role != "senior" && !resource.is_external };

Put the policy in `cedar_source` and give `tests` covering both an allowed case
(expected=true) and a denied case (expected=false).
"""


_CURRENT_POLICY_INSTRUCTIONS = """

CURRENT POLICY — the organization's policy today, which your output replaces:
{current}

Return the COMPLETE updated policy in `cedar_source`: every statement above that the
requirement does not change, plus the statements the requirement adds or changes. Do not drop
or weaken an existing statement unless the requirement says to. The current policy already
permits ordinary work, so do NOT add a blanket permit(principal, action, resource) — to
restrict something, add a forbid. Write `tests` about the requirement; a test about
one named agent must set `agent_id` to that agent.
"""


async def compile_nl_to_policy(
    nl_statement: str,
    client: LLMClient | None = None,
    *,
    current_policy: str | None = None,
    timeout_s: float | None = None,
    offline: bool = False,
) -> CompilerOutput:
    """Compile a natural language statement into a Cedar policy and auto-generate tests.

    Args:
        nl_statement: The English description of the policy.
        client: An optional backend. Defaults to whichever `AGENTIAM_LLM_BACKEND` selects.
        current_policy: The policy in force. When given, the model returns the whole updated
            policy and a template's statements are appended to it. When absent, the prompt is
            exactly the one the 30-case dataset was measured with.
        timeout_s: How long to wait for the model before falling back. `None` waits as long
            as the client does — which, with rate-limit backoff, can be minutes.
        offline: Skip the model entirely and use the template compiler.

    Returns:
        The compiled policy and tests, or a clarifying question; labelled with the compiler
        that produced it.
    """
    digest = statement_digest(nl_statement)
    if offline:
        return _from_templates(nl_statement, current_policy, reason="offline mode")

    prompt = f"{_SYSTEM_PROMPT}\n\nREQUIREMENT:\n{nl_statement}\n"
    if current_policy is not None:
        prompt += _CURRENT_POLICY_INSTRUCTIONS.format(current=current_policy.strip())
    schema: dict[str, Any] = CompilerOutput.model_json_schema()

    logger.info("compiling NL statement (sha256[:16]=%s, length=%d)", digest, len(nl_statement))
    try:
        model = client if client is not None else client_from_env()
        raw_output = await asyncio.wait_for(
            model.generate_structured(prompt=prompt, schema=schema), timeout=timeout_s
        )
        output = CompilerOutput.model_validate(raw_output)
        output.compiled_by, output.fallback_reason = "model", None
        return output
    except TimeoutError:
        reason = f"the model did not answer within {timeout_s} s"
    except LLMError as exc:
        reason = f"the model was unreachable ({exc})"
    except ValidationError:
        reason = "the model's answer was not in the expected shape"
    logger.warning("falling back to the template compiler for sha256[:16]=%s: %s", digest, reason)
    return _from_templates(nl_statement, current_policy, reason=reason)


def _from_templates(
    nl_statement: str, current_policy: str | None, *, reason: str
) -> CompilerOutput:
    """The template compiler's answer, or the shapes it knows when it has none."""
    # Imported here: `templates` builds `CompilerTestCase`s, so it imports this module.
    from agentiam_controlplane.nl_compiler.templates import SHAPES, compose, match

    found = match(nl_statement)
    if found is None:
        shapes = "; ".join(f'"{example}"' for _, example in SHAPES)
        return CompilerOutput(
            clarifying_question=(
                f"The offline compiler answered because {reason}, and it only understands "
                f"these shapes: {shapes}. Rephrase the rule as one of them, or edit the Cedar "
                f"directly."
            ),
            compiled_by="template",
            fallback_reason=reason,
        )
    source = compose(current_policy, found) if current_policy is not None else found.cedar
    return CompilerOutput(
        cedar_source=source,
        tests=found.tests,
        compiled_by="template",
        fallback_reason=reason,
    )
